from __future__ import annotations

import numpy as np

from perceval.utils import FockState
from perceval.components import ACircuit
import exqalibur as xq

from ._abstract_backends import ASamplingBackend
from ._naive import NaiveBackend


class MISBackend(ASamplingBackend):
    """
    Metropolised Independence Sampling (MIS) backend for boson sampling.

    The proposal distribution is generated by sampling each photon independently
    from |U|^2 (distinguishable photons), while acceptance uses the exact
    probability from a weak simulator.

    :param burn_in: number of initial steps discarded when initializing the chain
    :param thinning: number of intermediate steps discarded between returned samples
        (defaults to burn_in if omitted)
    :param seed: optional RNG seed for reproducibility
    """

    def __init__(self, burn_in: int = 0, thinning: int | None = None, seed: int | None = None):
        super().__init__()
        if burn_in < 0:
            raise ValueError("burn_in must be a non-negative integer")
        self._burn_in = int(burn_in)
        if thinning is None:
            self._thinning = self._burn_in
        else:
            if thinning < 0:
                raise ValueError("thinning must be a non-negative integer")
            self._thinning = int(thinning)
        self._rng = np.random.default_rng(seed)
        self._transition_probs = None
        self._input_modes = None
        self._current_state = None
        self._current_g = None
        self._current_p = None
        self._burned_in = False
        self._accepted_steps = 0
        self._rejected_steps = 0
        self._proposal_cols = None
        # Use Ryser (via Naive backend permanent computation) for target probabilities
        self._simulation_backend = NaiveBackend()

    @property
    def name(self) -> str:
        return "MIS"

    def set_circuit(self, circuit: ACircuit):
        super().set_circuit(circuit)
        # Element-wise |U|^2 cast to float for distinguishable proposal
        self._transition_probs = (np.abs(np.asarray(self._umat)) ** 2).astype(float)
        self._current_state = None
        self._current_g = None
        self._current_p = None
        self._burned_in = False
        self._accepted_steps = 0
        self._rejected_steps = 0
        self._proposal_cols = None
        self._simulation_backend.set_circuit(circuit)

    def set_input_state(self, input_state: FockState):
        super().set_input_state(input_state)
        self._input_modes = [mode for mode, count in enumerate(input_state) for _ in range(count)]
        self._current_state = None
        self._current_g = None
        self._current_p = None
        self._burned_in = False
        self._accepted_steps = 0
        self._rejected_steps = 0
        assert self._transition_probs is not None, "Transition probabilities must be initialized via set_circuit"
        self._proposal_cols = self._transition_probs[:, self._input_modes]
        self._simulation_backend.set_input_state(input_state)

    @property
    def acceptance_rate(self) -> float | None:
        total = self._accepted_steps + self._rejected_steps
        return None if total == 0 else self._accepted_steps / total

    def _distinguishable_proposal(self) -> tuple[FockState, float]:
        counts = [0] * self._circuit.m
        for mode in self._input_modes:
            probs = self._transition_probs[:, mode]
            chosen = self._rng.choice(self._circuit.m, p=probs)
            counts[chosen] += 1
        proposal_prob = self._proposal_probability(FockState(counts))
        return FockState(counts), proposal_prob

    def _proposal_probability(self, output_state: FockState) -> float:
        if self._input_state.n != output_state.n:
            return 0.0
        assert self._proposal_cols is not None, "Proposal columns not initialized"
        sub = self._build_submatrix(self._proposal_cols, output_state)
        if sub.size == 0:
            return 0.0
        # Distinguishable probability = permanent(|U|^2 submatrix) divided by output multiplicity factor
        perm = xq.permanent_fl(sub)
        norm = output_state.prodnfact()
        return 0.0 if norm == 0 else float(perm / norm)

    def _build_submatrix(self, matrix: np.ndarray, output_state: FockState) -> np.ndarray:
        n = self._input_state.n
        m = self._input_state.m
        if n != output_state.n:
            return np.zeros((0, 0), dtype=float)
        if n == 0:
            return np.ones((1, 1), dtype=float)
        sub = np.empty((n, n), dtype=float)
        colidx = 0
        # 'matrix' is already expanded in columns according to the input state
        for colidx in range(n):
            rowidx = 0
            for ok in range(m):
                for _ in range(output_state[ok]):
                    sub[rowidx, colidx] = matrix[ok, colidx]
                    rowidx += 1
        return sub

    def _target_probability(self, output_state: FockState) -> float:
        return self._simulation_backend.probability(output_state)

    def _ensure_chain(self):
        if self._current_state is None:
            self._current_state, self._current_g = self._distinguishable_proposal()
            self._current_p = self._target_probability(self._current_state)

        if not self._burned_in and self._burn_in > 0:
            for _ in range(self._burn_in):
                self._step_chain()
            self._burned_in = True

    def _step_chain(self):
        proposal_state, proposal_g = self._distinguishable_proposal()
        proposal_p = self._target_probability(proposal_state)

        if self._current_p == 0 and proposal_p > 0:
            accept = True
        elif proposal_g == 0:
            accept = False
        elif proposal_p == 0:
            accept = False
        else:
            ratio = (proposal_p * self._current_g) / (self._current_p * proposal_g)
            accept = self._rng.random() < min(1.0, ratio)

        if accept:
            self._current_state = proposal_state
            self._current_g = proposal_g
            self._current_p = proposal_p
            self._accepted_steps += 1
        else:
            self._rejected_steps += 1

    def sample(self):
        self._ensure_chain()
        self._step_chain()
        for _ in range(self._thinning):
            self._step_chain()
        return self._current_state

    def samples(self, count: int):
        self._ensure_chain()
        results = []
        for _ in range(count):
            self._step_chain()
            for _ in range(self._thinning):
                self._step_chain()
            results.append(self._current_state)
        return results
